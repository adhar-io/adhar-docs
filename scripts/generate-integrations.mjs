#!/usr/bin/env node
/**
 * Regenerates src/data/adharPackages.generated.ts — the list the /integrations
 * page is built from — out of the platform repository, so the page shows only
 * what Adhar actually ships.
 *
 *   node scripts/generate-integrations.mjs [--adhar ../adhar] [--ref origin/main]
 *
 * It reads, at <ref>, without touching the checkout:
 *   - every platform/stack/packages/<category>/<name>/adhar-package.yaml contract
 *   - the local, production and gitops ApplicationSets, for which packages each
 *     profile turns on by default
 * First-party `adhar-*` packages are Adhar itself, not an integration, and are left out.
 */
import { execFileSync } from "node:child_process";
import { writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import yaml from "js-yaml";

const here = dirname(fileURLToPath(import.meta.url));
const arg = (flag, fallback) => {
  const i = process.argv.indexOf(flag);
  return i > -1 ? process.argv[i + 1] : fallback;
};
const repo = resolve(arg("--adhar", join(here, "../../adhar")));
const ref = arg("--ref", "origin/main");
const git = (...a) => execFileSync("git", ["-C", repo, ...a], { encoding: "utf8", maxBuffer: 64 << 20 });

const commit = git("rev-parse", "--short", ref).trim();
const release = git("describe", "--tags", "--abbrev=0", ref).trim();

const PROFILES = { local: "adhar-appset-local.yaml", production: "adhar-appset-production.yaml", gitops: "adhar-appset-gitops.yaml" };
const enabledIn = {};
for (const [profile, file] of Object.entries(PROFILES)) {
  const appset = yaml.load(git("show", `${ref}:platform/stack/${file}`));
  for (const gen of appset.spec.generators) {
    for (const el of gen.list?.elements ?? []) {
      (enabledIn[el.name] ??= {})[profile] = String(el.enabled) === "true";
    }
  }
}

const contracts = git("ls-tree", "-r", "--name-only", ref, "platform/stack/packages")
  .split("\n")
  .filter((p) => p.endsWith("/adhar-package.yaml"));

const byName = new Map();
for (const path of contracts) {
  const c = yaml.load(git("show", `${ref}:${path}`));
  if (!c?.name || c.name.startsWith("adhar-") || byName.has(c.name)) continue;
  const profiles = enabledIn[c.name] ?? {};
  byName.set(c.name, {
    name: c.name,
    category: c.category,
    version: c.version ? String(c.version) : null,
    description: String(c.description ?? "").replace(/\s+/g, " ").trim(),
    homepage: c.homepage ?? null,
    license: c.license ?? null,
    stability: c.stability ?? null,
    plane: c.planeAffinity ?? null,
    upstreamChart: c.provenance?.upstreamChart ?? null,
    localSafe: c.resources?.localSafe ?? null,
    dependencies: (c.dependencies ?? []).map((d) => ({ name: d.name, optional: Boolean(d.optional) })),
    keywords: c.keywords ?? [],
    profiles: { local: profiles.local ?? false, production: profiles.production ?? false, gitops: profiles.gitops ?? false },
    path: dirname(path),
  });
}

const packages = [...byName.values()].sort((a, b) => a.name.localeCompare(b.name));
const out = `// Generated by scripts/generate-integrations.mjs from adhar ${release} (${commit}). Do not edit by hand.

export interface AdharPackage {
  name: string;
  category: string;
  version: string | null;
  description: string;
  homepage: string | null;
  license: string | null;
  stability: string | null;
  /** Which plane the package runs on: control-plane, data-plane, … */
  plane: string | null;
  upstreamChart: string | null;
  /** Whether it fits on a single local Kind node. */
  localSafe: boolean | null;
  dependencies: { name: string; optional: boolean }[];
  keywords: string[];
  /** On by default in each profile. */
  profiles: { local: boolean; production: boolean; gitops: boolean };
  /** The package's folder in the platform repository. */
  path: string;
}

export const ADHAR_PACKAGES_SOURCE = ${JSON.stringify({ release, commit })} as const;

export const ADHAR_PACKAGES: AdharPackage[] = ${JSON.stringify(packages, null, 2)};
`;
const target = join(here, "../src/data/adharPackages.generated.ts");
writeFileSync(target, out);
console.log(`wrote ${packages.length} packages from ${release} (${commit}) to ${target}`);
